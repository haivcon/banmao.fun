// Keep standalone on-chain motion identical to the preview's shared CSS block.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const css = fs.readFileSync(path.join(root, 'app/collection/banmaoking/banmaoking.css'), 'utf8');
const start = css.indexOf('.king-particles {');
const end = css.indexOf('@media (prefers-reduced-motion: reduce)', start);
if (start < 0 || end < 0) throw Error('Shared motion CSS markers not found');
const shared = css.slice(start, end).replace(/\/\*[\s\S]*?\*\//g, '').trim().replace(/\s+/g, ' ').replace(/\s*([{};,])\s*/g, '$1').replace(/:\s+/g, ':');
if (shared.includes("'")) throw Error('Escape Solidity quotes before syncing');
fs.writeFileSync(path.join(root, 'contracts/BanmaoKing/Lib/BanmaoKingMotionLib.sol'), `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.30;

// Generated by scripts/generate-king-motion.cjs. CSS only, no external resources.
library BanmaoKingMotionLib {
    function style() internal pure returns (string memory) {
        return '<style>${shared} @media (prefers-reduced-motion: reduce) { .king-art * { animation: none !important; } .king-particles { display: none; } }</style>';
    }
}
`);

// Split immutable CSS storage without changing a single byte of the SVG style.
const style = `<style>${shared} @media (prefers-reduced-motion: reduce) { .king-art * { animation: none !important; } .king-particles { display: none; } }</style>`;
const middle = Math.ceil(style.length / 2);
for (const [index, chunk] of [style.slice(0, middle), style.slice(middle)].entries()) {
  fs.appendFileSync(path.join(root, 'contracts/BanmaoKing/Lib/BanmaoKingMotionLib.sol'), `
contract BanmaoKingMotionPart${index} {
    function content() external pure returns (string memory) {
        return '${chunk}';
    }
}
`);
}

