const fs = require("node:fs");
const path = require("node:path");
const solc = require("solc");
const { createBanmaoBoxCompilerInput } = require("./banmaobox-runtime.cjs");

// Legacy virtual compiler source directory; this is not a physical path.
const VIRTUAL_SOURCE_DIR = "contracts/banmaobox";
const OUTPUT = "app/defi/box/generated/abis.ts";
const input = createBanmaoBoxCompilerInput({
  outputSelection: { "*": { "*": ["abi"] } },
  metadata: null,
});
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors || []).filter((error) => error.severity === "error");
if (errors.length) {
  throw new Error(errors.map((error) => error.formattedMessage).join("\n"));
}
const abi = (file, contract) =>
  output.contracts[`${VIRTUAL_SOURCE_DIR}/${file}`][contract].abi;
const erc20Abi = [
  {
    inputs: [],
    name: "decimals",
    outputs: [{ internalType: "uint8", name: "", type: "uint8" }],
    stateMutability: "view",
    type: "function",
  },
  {
    inputs: [],
    name: "symbol",
    outputs: [{ internalType: "string", name: "", type: "string" }],
    stateMutability: "view",
    type: "function",
  },
  {
    inputs: [{ internalType: "address", name: "account", type: "address" }],
    name: "balanceOf",
    outputs: [{ internalType: "uint256", name: "", type: "uint256" }],
    stateMutability: "view",
    type: "function",
  },
  {
    inputs: [
      { internalType: "address", name: "owner", type: "address" },
      { internalType: "address", name: "spender", type: "address" },
    ],
    name: "allowance",
    outputs: [{ internalType: "uint256", name: "", type: "uint256" }],
    stateMutability: "view",
    type: "function",
  },
  {
    inputs: [
      { internalType: "address", name: "spender", type: "address" },
      { internalType: "uint256", name: "amount", type: "uint256" },
    ],
    name: "approve",
    outputs: [{ internalType: "bool", name: "", type: "bool" }],
    stateMutability: "nonpayable",
    type: "function",
  },
];
const banner = `// Generated by npm run generate:banmaobox. Do not edit manually.\n`;
const generatedExports = [
  ["BANMAO_BOX_ABI", abi("BanmaoBox.sol", "BanmaoBox")],
  ["BANMAO_BOX_FACTORY_ABI", abi("BanmaoBoxFactory.sol", "BanmaoBoxFactory")],
  ["BANMAO_BOX_RENDERER_ABI", abi("BanmaoBoxRenderer.sol", "BanmaoBoxRenderer")],
  ["BANMAO_ERC20_ABI", erc20Abi],
]
  .map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)} as const;`)
  .join("\n\n");
fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, `${banner}${generatedExports}\n`);
console.log(`Generated ${OUTPUT} with solc ${solc.version()}`);
