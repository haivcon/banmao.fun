'use strict';
// Synchronize only Party Hat; preserve other authored accessory revisions.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
function load(file) {
  const context = { exports: {} };
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(root, file), 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS },
  }).outputText, context);
  return context.exports;
}
const { PARTY_HAT_SVG, BIRTHDAY_SCENE_SVG } = load('app/collection/banmaoking/accessory-polish.ts');
const { smilTargets } = load('app/collection/banmaoking/smil.ts');
const svg = PARTY_HAT_SVG.replace(/<(g|path|ellipse|circle|rect)\b[^<>]*class="([^"]+)"[^<>]*>/g, tag => {
  if (/\bid="/.test(tag)) return tag;
  const classes = tag.match(/class="([^"]+)"/)[1].split(/\s+/);
  const target = smilTargets.find(id => classes.includes(id));
  return target ? tag.replace('class=', `id="smil-${target}" class=`) : tag;
});
const file = path.join(root, 'contracts/BanmaoKing/Lib/BanmaoKingAccessoryLib.sol');
const source = fs.readFileSync(file, 'utf8');
const branch = /if \(id == 5\) return "<g [^\n]*";/g;
if ((source.match(branch) || []).length !== 1) throw Error('Expected one Party Hat render branch');
const generated = source.replace(branch, () => `if (id == 5) return ${JSON.stringify(svg)};`);
if (process.argv.includes('--check')) {
  if (source !== generated) throw Error('Party Hat catalogue is out of sync');
} else fs.writeFileSync(file, generated);
const sceneFile = path.join(root, 'contracts/BanmaoKing/Lib/BanmaoKingBirthdayLib.sol');
const sceneSource = '// SPDX-License-Identifier: MIT\npragma solidity ^0.8.30;\n// Generated by tools/sync-king-party-hat.cjs.\nlibrary BanmaoKingBirthdayLib {\n    function render() internal pure returns (string memory) {\n        return ' + JSON.stringify(BIRTHDAY_SCENE_SVG) + ';\n    }\n}\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(sceneFile) || fs.readFileSync(sceneFile, 'utf8') !== sceneSource) throw Error('Birthday scene is out of sync');
} else fs.writeFileSync(sceneFile, sceneSource);
console.log('Party Hat catalogue and independent birthday scene synchronized');
