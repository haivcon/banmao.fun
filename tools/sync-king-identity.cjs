'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'contracts/BanmaoKing/Lib/BanmaoKingIdentityLib.sol'),'utf8');
const constants={};
for(const m of source.matchAll(/string internal constant (\w+) = (['"])(.*?)\2;/g)) constants[m[1]]=m[3];
for(const m of source.matchAll(/uint256 internal constant (LOGO_CENTER_[XY]) = (\d+);/g)) constants[m[1]]=Number(m[2]);
const condition=source.match(/return (background ==[^;]+);/)[1].replaceAll('==','===');
const colors=[...source.matchAll(/return light\(background\) \? '([^']+)' : '([^']+)';/g)];
if(Object.keys(constants).length!==5||colors.length!==2)throw Error('Invalid identity contract');
const output='// Generated from BanmaoKingIdentityLib.sol; do not edit.\n'+Object.entries(constants).map(([k,v])=>`export const ${k} = ${JSON.stringify(v)};`).join('\n')+`\nexport function identityInk(background: number): string { return (${condition}) ? '${colors[0][1]}' : '${colors[0][2]}'; }\nexport function identityOutline(background: number): string { return (${condition}) ? '${colors[1][1]}' : '${colors[1][2]}'; }\n`;
const target=path.join(root,'app/collection/banmaoking/contract-identity.ts');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==output)throw Error('Run node tools/sync-king-identity.cjs');}else fs.writeFileSync(target,output);
console.log('Identity Solidity → frontend synchronized');
